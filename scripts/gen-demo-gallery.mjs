#!/usr/bin/env node
// Regenerate the open data demo gallery from scripts/demo-gallery.json:
//
// - docs/gallery.md — every demo, grouped by theme, one two-column table per
//   theme with a link to that theme's tag filter on share.geolibre.app.
// - the "Open data gallery" teaser on docs/demos.md, between the
//   <!-- demo-gallery-teaser:start/end --> markers (featured demos only).
//
// Usage: node scripts/gen-demo-gallery.mjs          # write both files
//        node scripts/gen-demo-gallery.mjs --check  # exit 1 if either is stale
//
// Screenshots live at https://assets.geolibre.app/images/<slug>.webp (added to
// opengeos/geolibre-assets); live projects at share.geolibre.app/<owner>/<slug>.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "scripts/demo-gallery.json"), "utf8"));
const galleryPath = join(root, "docs/gallery.md");
const demosPath = join(root, "docs/demos.md");
const TEASER_START = "<!-- demo-gallery-teaser:start -->";
const TEASER_END = "<!-- demo-gallery-teaser:end -->";

const escapeHtml = (text) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const projectUrl = (demo) => `https://share.geolibre.app/${data.owner}/${demo.slug}`;
const imageUrl = (demo) => `https://assets.geolibre.app/images/${demo.slug}.webp`;
const tagUrl = (tag) => `https://share.geolibre.app/explore?tag=${tag}`;
const anchor = (title) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function imageCell(demo) {
  return (
    `    <td width="50%"><a href="${projectUrl(demo)}"><img src="${imageUrl(demo)}" ` +
    `alt="GeoLibre map: ${escapeHtml(demo.title)}" loading="lazy"></a></td>`
  );
}

function captionCell(demo) {
  return (
    `    <td align="center"><b><a href="${projectUrl(demo)}">${escapeHtml(demo.title)}</a></b>` +
    `<br>${escapeHtml(demo.topic)} · ${escapeHtml(demo.caption)}` +
    `<br><small>Data: ${escapeHtml(demo.source)}</small></td>`
  );
}

/** A two-column tile table; an odd count ends on an empty cell. */
function table(demos) {
  const rows = [];
  for (let i = 0; i < demos.length; i += 2) {
    const pair = demos.slice(i, i + 2);
    const images = pair.map(imageCell);
    const captions = pair.map(captionCell);
    if (pair.length === 1) {
      images.push('    <td width="50%"></td>');
      captions.push("    <td></td>");
    }
    rows.push(`  <tr>\n${images.join("\n")}\n  </tr>`, `  <tr>\n${captions.join("\n")}\n  </tr>`);
  }
  return `<table>\n${rows.join("\n")}\n</table>\n`;
}

function renderGallery() {
  const counts = new Map(data.themes.map((t) => [t.tag, 0]));
  for (const demo of data.demos) {
    if (!counts.has(demo.theme)) throw new Error(`${demo.slug}: unknown theme ${demo.theme}`);
    counts.set(demo.theme, counts.get(demo.theme) + 1);
  }
  const jump = data.themes.map((t) => `[${t.title}](#${anchor(t.title)})`).join(" · ");
  const sections = data.themes.map((theme) => {
    const demos = data.demos
      .filter((d) => d.theme === theme.tag)
      .sort((a, b) => a.number - b.number);
    return (
      `## ${theme.title}\n\n${demos.length} projects · ` +
      `[Filter by the \`${theme.tag}\` tag](${tagUrl(theme.tag)})\n\n${table(demos)}`
    );
  });
  return `<!-- Generated by scripts/gen-demo-gallery.mjs from scripts/demo-gallery.json. Do not edit by hand. -->

# Gallery

${data.demos.length} interactive maps built from public open data, grouped by theme.
Each is a single \`.geolibre.json\` project authored with the
[Python package](python.md) and shared on share.geolibre.app: choropleths,
heatmaps, clusters, great-circle flows, 3D extrusions, before-and-after swipes,
and time sliders, with click popups, hover tooltips, and a legend derived from
each layer's symbology. **Click any map to open the live project**, or fork it
on share.geolibre.app to make it your own.

Every project is tagged with its theme, its features (\`time-slider\`, \`swipe\`,
\`3d\`, \`heatmap\`, \`clusters\`, \`imagery\`), and
[\`open-data\`](${tagUrl("open-data")}),
so you can filter the gallery on share.geolibre.app by tag.

[Browse the Official Demos collection](${data.collection}){ .md-button .md-button--primary }
[Watch the video tutorial](https://youtu.be/2r5OhvEa3AA){ .md-button }

Jump to a theme: ${jump}

${sections.join("\n")}`;
}

function renderTeaser() {
  const featured = data.featured.map((slug) => {
    const demo = data.demos.find((d) => d.slug === slug);
    if (!demo) throw new Error(`featured demo ${slug} is not in demos`);
    return demo;
  });
  return `${TEASER_START}
${data.demos.length} interactive maps built from public open data, from air quality and
earthquakes to Roman roads and the aurora, each a single \`.geolibre.json\`
project you can open live, explore, and fork. A few highlights:

${table(featured)}
[Browse the full gallery](gallery.md){ .md-button .md-button--primary }
[Official Demos collection](${data.collection}){ .md-button }
${TEASER_END}`;
}

function spliceTeaser(demosMarkdown) {
  const start = demosMarkdown.indexOf(TEASER_START);
  const end = demosMarkdown.indexOf(TEASER_END);
  if (start < 0 || end < start)
    throw new Error(`docs/demos.md is missing the ${TEASER_START} markers`);
  return (
    demosMarkdown.slice(0, start) + renderTeaser() + demosMarkdown.slice(end + TEASER_END.length)
  );
}

const outputs = [
  [galleryPath, renderGallery()],
  [demosPath, spliceTeaser(readFileSync(demosPath, "utf8"))],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => readFileSync(path, "utf8") !== text);
  for (const [path] of stale)
    console.error(`${path} is stale: run node scripts/gen-demo-gallery.mjs`);
  process.exit(stale.length ? 1 : 0);
}
for (const [path, text] of outputs) writeFileSync(path, text);
console.log(`Wrote docs/gallery.md (${data.demos.length} demos) and the docs/demos.md teaser.`);
