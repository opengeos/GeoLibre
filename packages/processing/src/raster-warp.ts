/**
 * In-browser raster warping: Resample, Reproject and Mosaic.
 *
 * The resampling kernels port GDAL's warp kernel (`gdalwarpkernel.cpp`, GDAL
 * 3.12) so a client run reproduces the rasterio sidecar on the same input:
 * destination pixel centres are mapped to source pixel coordinates (through
 * GDAL's approximate transformer, 0.125 px error, for a reprojection), then
 * sampled with nearest neighbour, the 4-sample bilinear / 16-sample cubic
 * formulas, or, when downsampling past a 0.95 scale, the widened
 * (scale-stretched) kernels GDAL switches to. Reproject's output grid ports
 * `GDALSuggestedWarpOutput2`, which `rasterio.warp.calculate_default_transform`
 * calls. `tests/raster-client-parity.test.ts` checks all of this against fixtures
 * generated by the real sidecar workers.
 */

/** Resampling methods both engines offer. */
export type WarpResampling = "nearest" | "bilinear" | "cubic";

/** NoData written where the source does not declare one (matches the terrain tools). */
const DEFAULT_NODATA = Number.NaN;

/** GDAL's approximate transformer error threshold (rasterio's `tolerance`). */
const APPROX_ERROR = 0.125;

/** Filter radius per method (GDAL `anGWKFilterRadius`). */
const FILTER_RADIUS: Record<WarpResampling, number> = {
  nearest: 0,
  bilinear: 1,
  cubic: 2,
};

/** Max output pixels for an in-browser warp (64 MP of Float32 per band). */
const MAX_WARP_PIXELS = 64_000_000;

function parseResampling(value: unknown): WarpResampling {
  const method = String(value ?? "nearest").toLowerCase();
  if (method === "nearest" || method === "bilinear" || method === "cubic") return method;
  throw new Error(`Unsupported resampling method: ${method}`);
}

function bilinearKernel(x: number): number {
  const a = Math.abs(x);
  return a <= 1 ? 1 - a : 0;
}

/** Keys cubic convolution kernel, a = -0.5 (GDAL `CubicKernel`). */
function cubicKernel(x: number): number {
  const a = Math.abs(x);
  if (a <= 1) return a * a * (1.5 * a - 2.5) + 1;
  if (a <= 2) return a * (a * (-0.5 * a + 2.5) - 4) + 2;
  return 0;
}

/** The four cubic weights for a fractional offset `d` (GDAL `GWKCubicComputeWeights`). */
function cubicWeights(d: number, out: Float64Array): void {
  out[0] = cubicKernel(1 + d);
  out[1] = cubicKernel(d);
  out[2] = cubicKernel(1 - d);
  out[3] = cubicKernel(2 - d);
}

/** Round a downsampling scale to the nearest integer reciprocal when within 0.05. */
function roundReciprocal(scale: number): number {
  if (scale >= 1) return scale;
  const reciprocal = 1 / scale;
  const n = Math.floor(reciprocal + 0.5);
  return Math.abs(reciprocal - n) < 0.05 ? 1 / n : scale;
}

/**
 * Maps a row of destination pixel coordinates (in place) to source pixel
 * coordinates; returns per-point success flags.
 */
type RowTransformer = (xs: Float64Array, ys: Float64Array) => Uint8Array;

/** Maps one destination pixel coordinate to a source pixel coordinate exactly. */
type PointTransformer = (x: number, y: number) => [number, number] | null;

interface WarpPlan {
  src: RasterData;
  dst: NorthUpGrid;
  method: WarpResampling;
  rowTransform: RowTransformer;
  exactTransform: PointTransformer;
}

/**
 * The resampling scale GDAL's warp kernel derives for a full-raster warp:
 * destination size over the raw (unpadded) source window the destination edges
 * map to, with GDAL's "same size" and integer-reciprocal adjustments.
 */
function kernelScales(plan: WarpPlan): { scaleX: number; scaleY: number } {
  const { src, dst, method, exactTransform } = plan;
  const steps = 21;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  const add = (x: number, y: number) => {
    const p = exactTransform(x, y);
    if (!p || !Number.isFinite(p[0]) || !Number.isFinite(p[1])) return;
    minX = Math.min(minX, p[0]);
    maxX = Math.max(maxX, p[0]);
    minY = Math.min(minY, p[1]);
    maxY = Math.max(maxY, p[1]);
  };
  const stepSize = 1 / (steps - 1);
  for (let ratio = 0; ratio <= 1 + stepSize * 0.5; ratio += stepSize) {
    add(ratio * dst.width, 0);
    add(ratio * dst.width, dst.height);
    add(0, ratio * dst.height);
    add(dst.width, ratio * dst.height);
  }
  if (!Number.isFinite(minX)) return { scaleX: 1, scaleY: 1 };
  const roundClose = (v: number) => (Math.abs(Math.round(v) - v) < 1e-6 ? Math.round(v) : v);
  minX = roundClose(minX);
  minY = roundClose(minY);
  maxX = roundClose(maxX);
  maxY = roundClose(maxY);

  const axis = (
    min: number,
    max: number,
    rasterSize: number,
    dstSize: number,
  ): { scale: number } => {
    const radius0 = FILTER_RADIUS[method];
    const windowScale = Math.max(1e-3, dstSize / (max - min));
    const radius = windowScale < 0.95 ? Math.ceil(radius0 / windowScale) : radius0;
    const minClamped = Math.trunc(Math.max(0, min));
    const maxClamped = Math.trunc(Math.min(Math.ceil(max), rasterSize));
    const sizeRaw = Math.max(0, Math.min(rasterSize - minClamped, max - min));
    let size: number;
    if (maxClamped - minClamped > 0.9 * rasterSize) {
      size = rasterSize;
    } else {
      const off = Math.max(0, Math.min(minClamped - radius, rasterSize));
      size = Math.max(0, Math.min(rasterSize - off, maxClamped - off + radius));
    }
    const extra = size - sizeRaw;
    let scale = dstSize / (size - extra);
    if (size >= dstSize && size <= dstSize + extra) scale = 1;
    return { scale: roundReciprocal(scale) };
  };
  return {
    scaleX: axis(minX, maxX, src.width, dst.width).scale,
    scaleY: axis(minY, maxY, src.height, dst.height).scale,
  };
}

/**
 * Port of GDAL's approximate transformer (`GDALApproxTransform`): transform a
 * scanline's start, middle and end exactly and interpolate linearly between
 * them while the middle's error stays under `maxError`, splitting otherwise.
 */
export function approxTransformRow(
  xs: Float64Array,
  ys: Float64Array,
  exact: (xs: Float64Array, ys: Float64Array, ok: Uint8Array) => void,
  maxError: number,
): Uint8Array {
  const n = xs.length;
  const ok = new Uint8Array(n);
  const nMiddle = (n - 1) >> 1;
  if (
    n <= 5 ||
    ys[0] !== ys[n - 1] ||
    ys[0] !== ys[nMiddle] ||
    xs[0] === xs[n - 1] ||
    xs[0] === xs[nMiddle] ||
    maxError === 0
  ) {
    exact(xs, ys, ok);
    return ok;
  }
  const sx = Float64Array.of(xs[0], xs[nMiddle], xs[n - 1]);
  const sy = Float64Array.of(ys[0], ys[nMiddle], ys[n - 1]);
  const sok = new Uint8Array(3);
  exact(sx, sy, sok);
  if (!sok[0] || !sok[1] || !sok[2]) {
    exact(xs, ys, ok);
    return ok;
  }
  approxInternal(xs, ys, ok, 0, n, sx, sy, exact, maxError);
  return ok;
}

function exactRange(
  xs: Float64Array,
  ys: Float64Array,
  ok: Uint8Array,
  start: number,
  count: number,
  exact: (xs: Float64Array, ys: Float64Array, ok: Uint8Array) => void,
): void {
  if (count <= 0) return;
  const subX = xs.subarray(start, start + count);
  const subY = ys.subarray(start, start + count);
  const subOk = ok.subarray(start, start + count);
  exact(subX, subY, subOk);
}

function approxInternal(
  xs: Float64Array,
  ys: Float64Array,
  ok: Uint8Array,
  off: number,
  n: number,
  sme: Float64Array,
  smeY: Float64Array,
  exact: (xs: Float64Array, ys: Float64Array, ok: Uint8Array) => void,
  maxError: number,
): void {
  const x = (i: number) => xs[off + i];
  const y = (i: number) => ys[off + i];
  const nMiddle = (n - 1) >> 1;
  const span = x(n - 1) - x(0);
  const dX = (sme[2] - sme[0]) / span;
  const dY = (smeY[2] - smeY[0]) / span;
  const err =
    Math.abs(sme[0] + dX * (x(nMiddle) - x(0)) - sme[1]) +
    Math.abs(smeY[0] + dY * (x(nMiddle) - x(0)) - smeY[1]);
  if (err > maxError) {
    const i0 = (nMiddle - 1) >> 1;
    const i1 = nMiddle - 1;
    const i2 = nMiddle + ((n - nMiddle - 1) >> 1);
    const midX = Float64Array.of(x(i0), x(i1), x(i2));
    const midY = Float64Array.of(y(i0), y(i1), y(i2));
    const baseHalf1 =
      nMiddle <= 5 || y(0) !== y(nMiddle - 1) || y(0) !== y(i0) || x(0) === x(i1) || x(0) === x(i0);
    const baseHalf2 =
      n - nMiddle <= 5 ||
      y(nMiddle) !== y(n - 1) ||
      y(nMiddle) !== y(i2) ||
      x(nMiddle) === x(n - 1) ||
      x(nMiddle) === x(i2);
    const midOk = Uint8Array.of(1, 1, 1);
    if (!baseHalf1 && !baseHalf2) exact(midX, midY, midOk);
    else if (!baseHalf1) exact(midX.subarray(0, 2), midY.subarray(0, 2), midOk.subarray(0, 2));
    else if (!baseHalf2) exact(midX.subarray(2), midY.subarray(2), midOk.subarray(2));
    const setSme = (i: number, k: number) => {
      xs[off + i] = sme[k];
      ys[off + i] = smeY[k];
      ok[off + i] = 1;
    };
    if (!midOk[0] || !midOk[1] || !midOk[2]) {
      exactRange(xs, ys, ok, off + 1, nMiddle - 1, exact);
      exactRange(xs, ys, ok, off + nMiddle + 1, n - nMiddle - 2, exact);
      setSme(0, 0);
      setSme(nMiddle, 1);
      setSme(n - 1, 2);
      return;
    }
    // The second half's start (the old middle) must survive the first half's
    // in-place rewrite of points [0, nMiddle), so it is read from `sme`.
    if (!baseHalf1) {
      approxInternal(
        xs,
        ys,
        ok,
        off,
        nMiddle,
        Float64Array.of(sme[0], midX[0], midX[1]),
        Float64Array.of(smeY[0], midY[0], midY[1]),
        exact,
        maxError,
      );
    } else {
      exactRange(xs, ys, ok, off + 1, nMiddle - 1, exact);
      setSme(0, 0);
    }
    if (!baseHalf2) {
      approxInternal(
        xs,
        ys,
        ok,
        off + nMiddle,
        n - nMiddle,
        Float64Array.of(sme[1], midX[2], sme[2]),
        Float64Array.of(smeY[1], midY[2], smeY[2]),
        exact,
        maxError,
      );
    } else {
      exactRange(xs, ys, ok, off + nMiddle + 1, n - nMiddle - 2, exact);
      setSme(nMiddle, 1);
      setSme(n - 1, 2);
    }
    return;
  }
  const x0 = x(0);
  for (let i = n - 1; i >= 0; i -= 1) {
    const dist = xs[off + i] - x0;
    xs[off + i] = sme[0] + dX * dist;
    ys[off + i] = smeY[0] + dY * dist;
    ok[off + i] = 1;
  }
}

/** Resample every band of `plan.src` onto `plan.dst`. */
function warp(plan: WarpPlan): { bands: Float32Array[]; nodata: number } {
  const { src, dst, method, rowTransform, exactTransform } = plan;
  if (
    dst.width * dst.height > MAX_WARP_PIXELS ||
    dst.width * dst.height * src.bands.length * 4 > 256 * 1024 * 1024
  ) {
    throw new Error(
      `The ${dst.width}x${dst.height} output is too large for the in-browser engine. Use the sidecar (rasterio/GDAL) engine instead.`,
    );
  }
  const { scaleX, scaleY } = kernelScales(plan);
  const use4 = scaleX >= 0.95 && scaleY >= 0.95;
  const W = src.width;
  const H = src.height;
  const srcNodata = src.nodata;
  const masked = srcNodata != null;
  const outNodata = DEFAULT_NODATA;
  const radius0 = FILTER_RADIUS[method];
  const xRadius = scaleX < 1 ? Math.ceil(radius0 / scaleX) : radius0;
  const yRadius = scaleY < 1 ? Math.ceil(radius0 / scaleY) : radius0;
  const kernel = method === "cubic" ? cubicKernel : bilinearKernel;
  const sx = Math.min(scaleX, 1);
  const sy = Math.min(scaleY, 1);

  const bands = src.bands.map(() => new Float32Array(dst.width * dst.height).fill(outNodata));
  const valid = (band: Float32Array, i: number): boolean => {
    if (!masked) return true;
    const v = band[i];
    return Number.isFinite(v) && v !== srcNodata;
  };

  const xs = new Float64Array(dst.width);
  const ys = new Float64Array(dst.width);
  const wx = new Float64Array(4);
  const wy = new Float64Array(4);

  /** GDAL 4-sample bilinear (masked or not). */
  const bilinear4 = (band: Float32Array, px: number, py: number): number | null => {
    let ix = Math.floor(px - 0.5);
    let iy = Math.floor(py - 0.5);
    let rx = 1.5 - (px - ix);
    let ry = 1.5 - (py - iy);
    if (masked) {
      if (ix === -1) {
        ix = 0;
        rx = 1;
      }
      if (iy === -1) {
        iy = 0;
        ry = 1;
      }
    }
    let acc = 0;
    let div = 0;
    const take = (c: number, r: number, w: number) => {
      if (c < 0 || c >= W || r < 0 || r >= H) return;
      const i = r * W + c;
      if (!valid(band, i)) return;
      div += w;
      acc += band[i] * w;
    };
    take(ix, iy, rx * ry);
    take(ix + 1, iy, (1 - rx) * ry);
    take(ix, iy + 1, rx * (1 - ry));
    take(ix + 1, iy + 1, (1 - rx) * (1 - ry));
    if (div < 0.00001) return masked ? null : 0;
    return div === 1 ? acc : acc / div;
  };

  /** GDAL 16-sample cubic, falling back to bilinear at borders/holes. */
  const cubic4 = (band: Float32Array, px: number, py: number): number | null => {
    const ix = Math.trunc(px - 0.5);
    const iy = Math.trunc(py - 0.5);
    if (ix - 1 < 0 || ix + 2 >= W || iy - 1 < 0 || iy + 2 >= H) return bilinear4(band, px, py);
    cubicWeights(px - 0.5 - ix, wx);
    cubicWeights(py - 0.5 - iy, wy);
    let acc = 0;
    for (let j = -1; j < 3; j += 1) {
      let row = 0;
      for (let i = -1; i < 3; i += 1) {
        const k = (iy + j) * W + ix + i;
        if (!valid(band, k)) return bilinear4(band, px, py);
        row += band[k] * wx[i + 1];
      }
      acc += row * wy[j + 1];
    }
    return acc;
  };

  /** GDAL's general (scale-stretched) kernel, used when downsampling. */
  const general = (band: Float32Array, px: number, py: number): number | null => {
    const ix = Math.floor(px - 0.5);
    const iy = Math.floor(py - 0.5);
    if (!masked && (ix >= W || iy >= H || xRadius > W || yRadius > H)) {
      return bilinear4(band, px, py);
    }
    const dx = px - 0.5 - ix;
    const dy = py - 0.5 - iy;
    const iMin = Math.max(1 - xRadius, -ix);
    const iMax = Math.min(xRadius, W - 1 - ix);
    const jMin = Math.max(1 - yRadius, -iy);
    const jMax = Math.min(yRadius, H - 1 - iy);
    let acc = 0;
    let weight = 0;
    for (let j = jMin; j <= jMax; j += 1) {
      const w1 = kernel((j - dy) * sy);
      const rowOff = (iy + j) * W + ix;
      for (let i = iMin; i <= iMax; i += 1) {
        const k = rowOff + i;
        const w2 = kernel((i - dx) * sx);
        if (masked) {
          if (!valid(band, k)) continue;
          acc += band[k] * w1 * w2;
          weight += w1 * w2;
        } else {
          acc += band[k] * w1 * w2;
        }
      }
    }
    if (!masked) {
      let sumX = Number.MIN_VALUE;
      for (let i = iMin; i <= iMax; i += 1) sumX += kernel((i - dx) * sx);
      let sumY = Number.MIN_VALUE;
      for (let j = jMin; j <= jMax; j += 1) sumY += kernel((j - dy) * sy);
      return acc / (sumX * sumY);
    }
    if (weight < 0.000001) return null;
    return weight < 0.99999 || weight > 1.00001 ? acc / weight : acc;
  };

  for (let row = 0; row < dst.height; row += 1) {
    for (let col = 0; col < dst.width; col += 1) {
      xs[col] = col + 0.5;
      ys[col] = row + 0.5;
    }
    const ok = rowTransform(xs, ys);
    for (let col = 0; col < dst.width; col += 1) {
      let px = xs[col];
      let py = ys[col];
      let success = ok[col] === 1;
      // GDAL's GWKCheckAndComputeSrcOffsets: a point just outside the source
      // from the approximate transformer is retried with the exact transform.
      for (let attempt = 0; attempt < 2; attempt += 1) {
        if (attempt === 1) {
          const p = exactTransform(col + 0.5, row + 0.5);
          success = p != null;
          if (p) [px, py] = p;
        }
        if (!success || Number.isNaN(px) || Number.isNaN(py)) {
          success = false;
          break;
        }
        const retry =
          (px < 0 && px > -1) ||
          (py < 0 && py > -1) ||
          (px + 1e-10 > W && px < W + 1) ||
          (py + 1e-10 > H && py < H + 1);
        const outside = px < 0 || py < 0 || px + 1e-10 > W || py + 1e-10 > H;
        if (!outside) break;
        if (attempt === 0 && retry) continue;
        success = false;
        break;
      }
      if (!success) continue;
      let ix = Math.trunc(px + 1e-10);
      let iy = Math.trunc(py + 1e-10);
      if (ix === W) ix -= 1;
      if (iy === H) iy -= 1;
      const centre = iy * W + ix;
      const di = row * dst.width + col;
      for (let b = 0; b < src.bands.length; b += 1) {
        const band = src.bands[b];
        // Masked kernels skip a destination pixel whose nearest source pixel
        // is NoData (GDAL ignores the multi-pixel footprint here).
        if (masked && !valid(band, centre)) continue;
        let value: number | null;
        if (method === "nearest" || W === 1 || H === 1) value = band[centre];
        else if (use4)
          value = method === "bilinear" ? bilinear4(band, px, py) : cubic4(band, px, py);
        else value = general(band, px, py);
        if (value == null || !Number.isFinite(Math.fround(value))) continue;
        bands[b][di] = value;
      }
    }
  }
  return { bands, nodata: outNodata };
}

/** An affine (no CRS change) source pixel transform for resample. */
function affinePlan(src: RasterData, dst: NorthUpGrid, method: WarpResampling): WarpPlan {
  const toSrc = (x: number, y: number): [number, number] => [
    (dst.originX + x * dst.resX - src.originX) / src.resX,
    (src.originY - (dst.originY - y * dst.resY)) / src.resY,
  ];
  return {
    src,
    dst,
    method,
    exactTransform: toSrc,
    rowTransform: (xs, ys) => {
      for (let i = 0; i < xs.length; i += 1) [xs[i], ys[i]] = toSrc(xs[i], ys[i]);
      return new Uint8Array(xs.length).fill(1);
    },
  };
}

export interface ResampleParams {
  resolution: number;
  resampling?: WarpResampling | string;
}

/**
 * Resample a raster to a new square pixel size in its own CRS, matching the
 * sidecar: the grid keeps the top-left corner and covers the full extent
 * (`ceil(span / resolution)` pixels per axis).
 */
export function resampleRaster(input: RasterData, params: ResampleParams): RasterData {
  const resolution = Number(params.resolution);
  if (!Number.isFinite(resolution) || resolution <= 0) {
    throw new Error("Target pixel size (resolution) must be > 0");
  }
  const method = parseResampling(params.resampling ?? "bilinear");
  const src = toNorthUp(input);
  const spanX = src.width * src.resX;
  const spanY = src.height * src.resY;
  const width = Math.max(1, Math.ceil(spanX / resolution - 1e-9));
  const height = Math.max(1, Math.ceil(spanY / resolution - 1e-9));
  const dst: NorthUpGrid = {
    width,
    height,
    originX: src.originX,
    originY: src.originY,
    resX: resolution,
    resY: resolution,
  };
  const { bands, nodata } = warp(affinePlan(src, dst, method));
  return { ...src, ...dst, bands, nodata };
}

/** Parse a client-supported target CRS ("EPSG:NNNN") to its EPSG code. */
export function parseEpsgCode(value: unknown): number {
  const text = String(value ?? "").trim();
  if (!text) throw new Error("Target CRS (dst_crs) is required");
  const match = /^(?:EPSG\s*:\s*)?(\d+)$/i.exec(text);
  if (!match) {
    throw new Error(
      `The in-browser engine reprojects to EPSG codes only (got "${text}"). Use an authority code such as EPSG:3857, or the sidecar (rasterio/GDAL) engine for WKT/PROJ strings.`,
    );
  }
  return Number(match[1]);
}

function isGeographicDefinition(definition: string): boolean {
  return (
    definition === "EPSG:4326" || /\+proj=(?:longlat|latlong|lonlat|latlon)\b/.test(definition)
  );
}

/**
 * Port of `GDALSuggestedWarpOutput2` for a north-up source: sample the source
 * edges into the target CRS, take their bounds, and size square pixels from the
 * transformed top-left to bottom-right diagonal.
 */
export function suggestedWarpOutput(
  src: NorthUpGrid,
  forward: CoordTransform,
  targetIsGeographic: boolean,
): NorthUpGrid {
  const W = src.width;
  const H = src.height;
  let steps = Math.floor(Math.min(W, H) / 50 + 0.5);
  steps = Math.min(100, Math.max(20, steps));
  const step = 1 / steps;
  const pts: [number, number][] = [];
  const top: [number, number][] = [];
  const bottom: [number, number][] = [];
  const left: [number, number][] = [];
  const right: [number, number][] = [];
  for (let i = 0; i <= steps; i += 1) {
    const ratio = i === steps ? 1 : i * step;
    top.push([ratio * W, 0]);
    bottom.push([ratio * W, H]);
    left.push([0, ratio * H]);
    right.push([W, ratio * H]);
  }
  pts.push(...top, ...bottom, ...left, ...right);
  const out = pts.map(([px, py]) => {
    try {
      const p = forward([src.originX + px * src.resX, src.originY - py * src.resY]);
      return Number.isFinite(p[0]) && Number.isFinite(p[1]) ? p : null;
    } catch {
      return null;
    }
  });
  if (out.some((p) => p == null)) {
    throw new Error(
      "Part of the raster cannot be transformed to the target CRS in the browser. Use the sidecar (rasterio/GDAL) engine instead.",
    );
  }
  const good = out as [number, number][];
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const [x, y] of good) {
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  }
  let dX = good[good.length - 1][0] - good[0][0];
  let dY = good[good.length - 1][1] - good[0][1];
  if (dX === 0 || dY === 0) {
    dX = maxX - minX;
    dY = maxY - minY;
  }
  const pixelSize = Math.sqrt(dX * dX + dY * dY) / Math.sqrt(W * W + H * H);
  const width = Math.trunc((maxX - minX) / pixelSize + 0.5);
  const height = Math.trunc((maxY - minY) / pixelSize + 0.5);
  if (width < 1 || height < 1) throw new Error("The reprojected raster would be empty.");
  let resX = pixelSize;
  const newMaxX = minX + width * pixelSize;
  if (targetIsGeographic && ((maxX <= 180 && newMaxX > 180) || maxX === 180)) {
    resX = (180 - minX) / width;
  }
  let resY = pixelSize;
  const newMinY = maxY - height * pixelSize;
  if (targetIsGeographic && minY >= -90 && newMinY < -90) {
    resY = (maxY + 90) / height;
  }
  return { width, height, originX: minX, originY: maxY, resX, resY };
}

export interface ReprojectParams {
  dst_crs: string;
  resampling?: WarpResampling | string;
}

/**
 * Warp a raster to another CRS (EPSG code) the way the sidecar does with
 * `calculate_default_transform` + `rasterio.warp.reproject`.
 */
export async function reprojectRaster(
  input: RasterData,
  params: ReprojectParams,
): Promise<RasterData> {
  const method = parseResampling(params.resampling ?? "nearest");
  const code = parseEpsgCode(params.dst_crs);
  const src = toNorthUp(input);
  const srcDef = await rasterCrsDefinition(src, "reproject");
  const dstDef = await epsgDefinition(code);
  const targetGeographic = isGeographicDefinition(dstDef);
  const toDst = await crsTransform(srcDef, dstDef);
  const toSrc = await crsTransform(dstDef, srcDef);
  const sameCrs = rasterEpsg(src) === code;
  const dst = sameCrs
    ? {
        width: src.width,
        height: src.height,
        originX: src.originX,
        originY: src.originY,
        resX: src.resX,
        resY: src.resY,
      }
    : suggestedWarpOutput(src, toDst, targetGeographic);

  const exactInto = (xs: Float64Array, ys: Float64Array, ok: Uint8Array) => {
    for (let i = 0; i < xs.length; i += 1) {
      try {
        const [gx, gy] = toSrc([dst.originX + xs[i] * dst.resX, dst.originY - ys[i] * dst.resY]);
        if (!Number.isFinite(gx) || !Number.isFinite(gy)) {
          ok[i] = 0;
          continue;
        }
        xs[i] = (gx - src.originX) / src.resX;
        ys[i] = (src.originY - gy) / src.resY;
        ok[i] = 1;
      } catch {
        ok[i] = 0;
      }
    }
  };
  const plan: WarpPlan = {
    src,
    dst,
    method,
    rowTransform: (xs, ys) => approxTransformRow(xs, ys, exactInto, APPROX_ERROR),
    exactTransform: (x, y) => {
      const xs = Float64Array.of(x);
      const ys = Float64Array.of(y);
      const ok = new Uint8Array(1);
      exactInto(xs, ys, ok);
      return ok[0] ? [xs[0], ys[0]] : null;
    },
  };
  const { bands, nodata } = warp(plan);
  return {
    ...src,
    ...dst,
    bands,
    nodata,
    geoKeys: geoKeysForEpsg(code, targetGeographic),
  };
}

export type MosaicMethod = "first" | "last" | "min" | "max";

/**
 * Merge rasters sharing a CRS, pixel size and pixel grid into one covering
 * their union, like `rasterio.merge.merge` in the sidecar. Inputs on a
 * different grid would need resampling, which only the sidecar does.
 */
export function mosaicRasters(
  inputs: RasterData[],
  methodValue: unknown,
): { raster: RasterData; messages: string[] } {
  const method = String(methodValue ?? "first").toLowerCase() as MosaicMethod;
  if (!["first", "last", "min", "max"].includes(method)) {
    throw new Error(`Unsupported merge method: ${method} (use first, last, max, min)`);
  }
  if (inputs.length < 2) throw new Error("Mosaic needs at least two rasters");
  const rasters = inputs.map(toNorthUp);
  const first = rasters[0];
  const firstEpsg = rasterEpsg(first);
  if (firstEpsg === null) {
    throw new Error(
      "Mosaic requires a known EPSG CRS for every input; resolve or reproject custom/unknown CRSs with the sidecar first.",
    );
  }
  for (const r of rasters.slice(1)) {
    if (rasterEpsg(r) !== firstEpsg) {
      throw new Error("All rasters must share the same CRS; reproject them first.");
    }
    if (r.bands.length !== first.bands.length) {
      throw new Error(
        `All rasters must have the same band count; one has ${r.bands.length} but the first has ${first.bands.length}.`,
      );
    }
    const offX = (r.originX - first.originX) / first.resX;
    const offY = (first.originY - r.originY) / first.resY;
    if (
      Math.abs(r.resX - first.resX) > 1e-6 * Math.abs(first.resX) ||
      Math.abs(r.resY - first.resY) > 1e-6 * Math.abs(first.resY) ||
      Math.abs(offX - Math.round(offX)) > 1e-3 ||
      Math.abs(offY - Math.round(offY)) > 1e-3
    ) {
      throw new Error(
        "The in-browser mosaic needs inputs on the same pixel grid (equal pixel size, aligned origins). Use the sidecar (rasterio/GDAL) engine to resample misaligned rasters.",
      );
    }
  }
  const messages: string[] = [];
  for (const r of rasters.slice(1)) {
    if (r.nodata !== first.nodata && !(Number.isNaN(r.nodata) && Number.isNaN(first.nodata))) {
      messages.push(
        `Warning: inputs have different nodata values (${first.nodata} vs ${r.nodata}); output nodata is NaN.`,
      );
    }
  }
  const { resX, resY } = first;
  const minX = Math.min(...rasters.map((r) => r.originX));
  const maxY = Math.max(...rasters.map((r) => r.originY));
  const maxX = Math.max(...rasters.map((r) => r.originX + r.width * r.resX));
  const minY = Math.min(...rasters.map((r) => r.originY - r.height * r.resY));
  const width = Math.max(1, Math.ceil((maxX - minX) / resX - 1e-9));
  const height = Math.max(1, Math.ceil((maxY - minY) / resY - 1e-9));
  const pixels = width * height;
  if (
    !Number.isSafeInteger(pixels) ||
    pixels > MAX_WARP_PIXELS ||
    pixels * first.bands.length * 5 > 256 * 1024 * 1024
  )
    throw new RangeError(
      "The mosaic union exceeds the browser allocation budget. Crop the extent or use the sidecar (rasterio/GDAL) engine.",
    );
  const outNodata = DEFAULT_NODATA;
  const bands = first.bands.map(() => new Float32Array(width * height).fill(outNodata));
  // Per-band "already written" flags: rasterio decides per band value whether
  // the destination still holds NoData.
  const filled = first.bands.map(() => new Uint8Array(width * height));
  for (const r of rasters) {
    const colOff = Math.round((r.originX - minX) / resX);
    const rowOff = Math.round((maxY - r.originY) / resY);
    for (let row = 0; row < r.height; row += 1) {
      const dr = row + rowOff;
      if (dr < 0 || dr >= height) continue;
      for (let col = 0; col < r.width; col += 1) {
        const dc = col + colOff;
        if (dc < 0 || dc >= width) continue;
        const si = row * r.width + col;
        const di = dr * width + dc;
        for (let b = 0; b < bands.length; b += 1) {
          const v = r.bands[b][si];
          if (!Number.isFinite(v) || (r.nodata != null && v === r.nodata)) continue;
          const out = bands[b];
          if (!filled[b][di] || method === "last") out[di] = v;
          else if (method === "min") out[di] = Math.min(out[di], v);
          else if (method === "max") out[di] = Math.max(out[di], v);
          filled[b][di] = 1;
        }
      }
    }
  }
  return {
    raster: {
      ...first,
      bands,
      width,
      height,
      originX: minX,
      originY: maxY,
      nodata: outNodata,
    },
    messages,
  };
}
