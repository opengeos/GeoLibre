const metadataById = new Map<string, BuiltInPluginMetadata>(
  BUILT_IN_PLUGIN_METADATA.map((metadata) => [metadata.id, metadata]),
);

/** Resolve a known built-in id without loading its implementation. */
export function builtInPluginMetadata(id: BuiltInPluginId): BuiltInPluginMetadata {
  const metadata = metadataById.get(id);
  if (!metadata) throw new Error(`Unknown built-in plugin '${id}'.`);
  return metadata;
}

/** Copy runtime metadata while keeping mutable plugin arrays independent. */
export function builtInPluginProperties(id: BuiltInPluginId) {
  const metadata = builtInPluginMetadata(id);
  return {
    id: metadata.id,
    name: metadata.name,
    version: metadata.version,
    activeByDefault: metadata.activeByDefault,
    engines: metadata.engines ? [...metadata.engines] : undefined,
    exclusiveGroup: metadata.exclusiveGroup,
    assistant: metadata.assistant ? { ...metadata.assistant } : undefined,
    urlParameterNames: metadata.urlParameterNames ? [...metadata.urlParameterNames] : undefined,
    restoresPanelCollapseState: metadata.restoresPanelCollapseState,
    clearsStateOnProjectLoad: metadata.clearsStateOnProjectLoad,
    sessionScoped: metadata.sessionScoped,
  };
}

/** Preserve a factory instance's identity while assigning canonical metadata. */
export function defineBuiltInPlugin<Plugin extends GeoLibrePlugin>(
  id: BuiltInPluginId,
  plugin: Plugin,
): Plugin {
  if (plugin.id !== id) throw new Error(`The factory for '${id}' returned a different plugin.`);
  return Object.assign(plugin, builtInPluginProperties(id));
}
