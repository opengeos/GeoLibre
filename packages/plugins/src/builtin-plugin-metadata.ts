export type BuiltInPluginId<Category extends BuiltInPluginCategory = BuiltInPluginCategory> =
  Extract<(typeof BUILT_IN_PLUGIN_METADATA)[number], { readonly category: Category }>["id"];

/** Resolve menu groups without importing the implementations that belong to them. */
export function builtInPluginIds<Category extends BuiltInPluginCategory>(
  category: Category,
): readonly BuiltInPluginId<Category>[] {
  const entries: BuiltInPluginMetadata[] = BUILT_IN_PLUGIN_METADATA.filter(
    (metadata) => metadata.category === category,
  );
  // Filtering establishes the id/category association erased by the shared
  // metadata interface used to sort optional group positions.
  return entries
    .sort((left, right) => (left.categoryOrder ?? 0) - (right.categoryOrder ?? 0))
    .map(({ id }) => id) as BuiltInPluginId<Category>[];
}

